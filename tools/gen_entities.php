<?php
// Generates src/builtins/entities.rs: the HTML entity tables of htmlentities()
// and html_entity_decode(). Usage: php tools/gen_entities.php entities.json
// (WHATWG's https://html.spec.whatwg.org/entities.json) > src/builtins/entities.rs
$json = json_decode(file_get_contents($argv[1]), true);
function cps(string $s): array { return array_map('mb_ord', mb_str_split($s, 1, 'UTF-8')); }
function lit(string $s): string { return '"' . addcslashes($s, "\"\\") . '"'; }
echo "//! Generated by tools/gen_entities.php: do not edit.\n";
echo "//! HTML entity names and the code points they stand for.\n\n";
// HTML 4.01: one name per character, as get_html_translation_table() lists them
$html4 = [];
foreach (get_html_translation_table(HTML_ENTITIES, ENT_QUOTES | ENT_HTML401, 'UTF-8') as $char => $ent) {
    if ($ent[1] === '#') continue;
    $html4[substr($ent, 1, -1)] = cps($char)[0];
}
ksort($html4, SORT_STRING);
echo "/// HTML 4.01 entities (also XHTML's), sorted by name\npub const HTML4: &[(&str, u32)] = &[\n";
foreach ($html4 as $n => $cp) echo "    (", lit($n), ", $cp),\n";
echo "];\n\n";
// HTML 5: every name ending in `;`, for decoding
$html5 = [];
foreach ($json as $name => $info) {
    if (substr($name, -1) !== ';') continue;
    $cp = $info['codepoints'];
    $html5[substr($name, 1, -1)] = [$cp[0], $cp[1] ?? 0];
}
ksort($html5, SORT_STRING);
echo "/// HTML 5 entities with their one or two code points (0: none), sorted by name\npub const HTML5: &[(&str, u32, u32)] = &[\n";
foreach ($html5 as $n => [$a, $b]) echo "    (", lit($n), ", $a, $b),\n";
echo "];\n\n";
// HTML 5 encoding: the name htmlentities() picks for a character or a pair
$enc = [];
foreach (get_html_translation_table(HTML_ENTITIES, ENT_QUOTES | ENT_HTML5, 'UTF-8') as $chars => $ent) {
    $c = cps($chars);
    $enc[] = [$c[0], $c[1] ?? 0, substr($ent, 1, -1)];
}
usort($enc, fn($x, $y) => [$x[0], $x[1]] <=> [$y[0], $y[1]]);
echo "/// htmlentities() names for HTML 5, by code point (and the following one, 0: any)\npub const HTML5_ENCODE: &[(u32, u32, &str)] = &[\n";
foreach ($enc as [$a, $b, $n]) echo "    ($a, $b, ", lit($n), "),\n";
echo "];\n";
