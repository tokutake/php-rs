#!/usr/bin/env python3
"""Generates src/regex/ucd.rs from PCRE2's Unicode tables.

Usage: gen_ucd.py <pcre2 src dir> > src/regex/ucd.rs

Reads pcre2_ucd.c (the character database), pcre2_ucptables.c (property
names), pcre2_ucp.h (the enums) and pcre2_tables.c (grapheme break rules)
from a PCRE2 release, so that \\p, \\X and caseless matching behave exactly
like the PCRE2 that php-src links against.
"""
import re
import sys

src = sys.argv[1]


def read(name):
    with open(f"{src}/{name}", encoding="utf-8") as f:
        return f.read()


ucd = read("pcre2_ucd.c")
ucp_h = read("pcre2_ucp.h")
ucptables = read("pcre2_ucptables.c")
tables = read("pcre2_tables.c")

# Enum values: every `ucp_Name` gets its position within its enum
enum_value = {}
for body in re.findall(r"enum \{(.*?)\};", ucp_h, re.S):
    names = re.findall(r"^\s*(ucp_\w+)", body, re.M)
    for i, n in enumerate(names):
        enum_value[n] = i


def array(name, typ=r"uint(?:16|32)_t"):
    # The last definition: the first ones are dummies for builds without Unicode
    m = re.findall(r"const " + typ + r" PRIV\(" + name + r"\)\[\] = \{(.*?)\};", ucd, re.S)[-1]
    body = re.sub(r"/\*.*?\*/", "", m, flags=re.S)
    body = body.replace("NOTACHAR", "0xffffffff")
    return [int(x.rstrip("u"), 0) for x in re.findall(r"0x[0-9a-fA-F]+u?|\d+", body)]


m = re.findall(r"const ucd_record PRIV\(ucd_records\)\[\] = \{(.*?)\n\};", ucd, re.S)[-1]
m = re.sub(r"/\*.*?\*/", "", m, flags=re.S)
records = [tuple(int(x) for x in r.split(",") if x.strip()) for r in re.findall(r"\{([^}]*)\}", m)]

stage1 = array("ucd_stage1")
stage2 = array("ucd_stage2")
caseless = array("ucd_caseless_sets")
script_sets = array("ucd_script_sets")
boolprop_sets = array("ucd_boolprop_sets")
script_item = int(re.search(r"#define ucd_script_sets_item_size (\d+)", ucp_h).group(1))
bool_item = int(re.search(r"#define ucd_boolprop_sets_item_size (\d+)", ucp_h).group(1))

# Property names, in utt_names order (which is sorted)
strings = {}
for name, body in re.findall(r"#define (STRING_\w+0) (.*)", ucptables):
    text = ""
    for tok in re.findall(r"STR_(\w+)", body):
        text += {"AMPERSAND": "&", "UNDERSCORE": "_"}.get(tok, tok if len(tok) == 1 else "?")
    strings[name] = text.lower()
order = re.search(r"const char PRIV\(utt_names\)\[\] =(.*?);", ucptables, re.S).group(1).split()
utt = re.findall(r"\{\s*\d+,\s*(PT_\w+),\s*(\w+)\s*\}", ucptables)
assert len(order) == len(utt)
props = []
for sname, (ptype, value) in zip(order, utt):
    v = enum_value[value] if value.startswith("ucp_") else int(value)
    props.append((strings[sname], ptype[3:], v))

# Grapheme break table
gb = re.search(r"const uint32_t PRIV\(ucp_gbtable\)\[\] = \{(.*?)\};", tables, re.S).group(1)
gb = re.sub(r"/\*.*?\*/", "", gb, flags=re.S)
gb = re.sub(r"ucp_gb\w+", lambda m: str(enum_value[m.group(0)]), gb)
esz = f"(1<<{enum_value['ucp_gbExtend']})|(1<<{enum_value['ucp_gbSpacingMark']})|(1<<{enum_value['ucp_gbZWJ']})"
gb = gb.replace("ESZ", esz).replace("1u", "1")
gbtable = [eval(" ".join(x.split())) for x in gb.split(",") if x.strip()]

license_text = re.search(r"-{70,}\n(.*?)\n-{70,}", ucd, re.S).group(1)

out = []
w = out.append
w("//! Unicode character database, generated by tools/gen_ucd.py from the")
w("//! tables of PCRE2 10.42 (Unicode " + re.search(r'unicode_version\) = "([\d.]+)"', ucd).group(1) + "). Do not edit.")
w("//!")
w("//! PCRE2: Copyright (c) 1997-2012 University of Cambridge,")
w("//! Copyright (c) 2016-2022 University of Cambridge. Distributed under this licence:")
w("//!")
for line in license_text.splitlines():
    w(("//! " + line).rstrip())
w("")
w("#![allow(clippy::unreadable_literal)]")
w("")


def emit(name, typ, values, per_line=16):
    w(f"pub static {name}: [{typ}; {len(values)}] = [")
    for i in range(0, len(values), per_line):
        w("    " + ", ".join(str(v) for v in values[i:i + per_line]) + ",")
    w("];")
    w("")


w("/// (script, chartype, grapheme break, caseless set, other case offset, script extension | bidi class << 11, binary properties)")
w(f"pub static RECORDS: [(u8, u8, u8, u8, i32, u16, u16); {len(records)}] = [")
for r in records:
    w("    (" + ", ".join(str(x) for x in r) + "),")
w("];")
w("")
emit("STAGE1", "u16", stage1)
emit("STAGE2", "u16", stage2)
w("/// Lists of characters that are all the same caselessly, each ending with u32::MAX")
emit("CASELESS_SETS", "u32", [hex(x) for x in caseless], 8)
w(f"/// Script extension bitmaps, {script_item} words each")
emit("SCRIPT_SETS", "u32", [hex(x) for x in script_sets], 6)
w(f"/// Binary property bitmaps, {bool_item} words each")
emit("BOOLPROP_SETS", "u32", [hex(x) for x in boolprop_sets], 6)
w("/// Pairs of grapheme break properties between which there is no break")
emit("GB_TABLE", "u32", [hex(x) for x in gbtable], 4)
w("#[derive(Clone, Copy, PartialEq, Eq, Debug)]")
w("pub enum PropType {")
for t in sorted({p[1] for p in props}):
    w(f"    {t.capitalize()},")
w("}")
w("")
w("/// Property names for \\p, sorted, with separators removed and lowercased")
w(f"pub static PROPERTIES: [(&str, PropType, u16); {len(props)}] = [")
for name, t, v in props:
    w(f'    ("{name}", PropType::{t.capitalize()}, {v}),')
w("];")
w("")
for n in ["ucp_gbRegional_Indicator", "ucp_gbExtend", "ucp_gbZWJ",
          "ucp_gbExtended_Pictographic"]:
    w(f"pub const {n[4:].upper()}: u8 = {enum_value[n]};")
print("\n".join(out))
