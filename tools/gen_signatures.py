#!/usr/bin/env python3
"""Generates src/builtins/signatures.rs: parameter names and defaults of the
built-ins php-rs implements, taken from php-src's stub files, for named
arguments. Usage: tools/gen_signatures.py STUB_DIR > src/builtins/signatures.rs
(the stubs are e.g. ext/standard/basic_functions.stub.php of the php-src
branch being followed)."""
import os, re, sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))

def implemented():
    names = set()
    for dirpath, _, files in os.walk(os.path.join(ROOT, 'src')):
        for f in files:
            if f.endswith('.rs'):
                src = open(os.path.join(dirpath, f)).read()
                for block in re.findall(r'NAMES: &\[&str\] = &\[(.*?)\];', src, re.S):
                    names.update(re.findall(r'"([a-z0-9_]+)"', block))
    return names

def split_params(s):
    parts, depth, cur, quote, escaped = [], 0, '', None, False
    for c in s:
        if quote:
            cur += c
            if escaped:
                escaped = False
            elif c == '\\':
                escaped = True
            elif c == quote:
                quote = None
            continue
        if c in '"\'':
            quote = c
        elif c in '([':
            depth += 1
        elif c in ')]':
            depth -= 1
        elif c == ',' and depth == 0:
            parts.append(cur)
            cur = ''
            continue
        cur += c
    if cur.strip():
        parts.append(cur)
    return parts

# Defaults php-rs cannot evaluate, and what they stand for
REPLACE = {'RoundingMode::HalfAwayFromZero': 'PHP_ROUND_HALF_UP'}

def params(s):
    out = []
    for p in split_params(s):
        p = re.sub(r'#\[[^\]]*\]', '', p).strip()
        m = re.match(r'(?:.*?\s)?(&)?\s*(\.\.\.)?\$(\w+)\s*(?:=\s*(.*))?$', p, re.S)
        if not m:
            raise SystemExit(f'cannot parse parameter {p!r}')
        by_ref, variadic, name, default = m.groups()
        if default is not None:
            default = ' '.join(default.split())
            default = REPLACE.get(default, default)
        out.append((name, default, bool(variadic), bool(by_ref)))
    return out

def main():
    want = implemented()
    sigs = {}
    for f in sorted(os.listdir(sys.argv[1])):
        src = open(os.path.join(sys.argv[1], f)).read()
        src = re.sub(r'/\*.*?\*/', '', src, flags=re.S)
        cls = None
        for m in re.finditer(r'(?:^|\n)\s*(?:final\s+|abstract\s+)*(class|interface)\s+(\w+)|function\s+(\w+)\s*\((.*?)\)\s*(?::\s*[^{;]+)?\s*[{;]', src, re.S):
            if m.group(1):
                cls = m.group(2)
                continue
            name, ps = m.group(3), m.group(4)
            indented = src.rfind('\n', 0, m.start(3)) < m.start(3) - len('function ') - 1
            key = f'{cls.lower()}::{name.lower()}' if cls and indented else name.lower()
            if key in want or (cls and indented and cls in ('Exception', 'Error', 'Generator', 'Closure')):
                sigs.setdefault(key, params(ps))
    print('//! Generated by tools/gen_signatures.py from php-src\'s stubs: do not edit.')
    print('//! Parameter names and default values (as PHP source) for named arguments.')
    print()
    print('use super::Param;')
    print()
    print('pub const SIGNATURES: &[(&str, &[Param])] = &[')
    for key in sorted(sigs):
        items = []
        for name, default, variadic, by_ref in sigs[key]:
            d = 'None' if default is None else 'Some(' + ('"' + default.replace('\\', '\\\\').replace('"', '\\"') + '"') + ')'
            items.append(f'Param {{ name: "{name}", default: {d}, variadic: {str(variadic).lower()}, by_ref: {str(by_ref).lower()} }}')
        print(f'    ("{key}", &[')
        for it in items:
            print(f'        {it},')
        print('    ]),')
    print('];')
    missing = sorted(n for n in want if n not in sigs)
    if missing:
        print('missing: ' + ' '.join(missing), file=sys.stderr)

main()
