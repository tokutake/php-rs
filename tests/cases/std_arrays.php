function json_like($v) {
    if (is_array($v)) {
        $parts = [];
        foreach ($v as $k => $x) $parts[] = (is_int($k) ? $k : "'$k'") . "=>" . json_like($x);
        return "[" . implode(", ", $parts) . "]";
    }
    return var_export($v, true);
}
